import { mkdir, readFile, writeFile, cp, readdir, rm, lstat, realpath } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';
import { buildCloudflare, buildWasm } from './cloudflare.mjs';
import RefParser from '@apidevtools/json-schema-ref-parser';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import { writeAppNotices, writeCoreNotices } from './notices.mjs';
import { apps, appHTML } from './apps.mjs';
import { browserOptions, coreOptions } from './bundle-options.mjs';

const target = process.argv[2] ?? 'all';
if (!['all', 'core', 'cloudflare', ...apps].includes(target)) throw new Error('Build target must be core, demo, playpen, cloudflare or all.');
const dist = resolve(process.env.TASM_DIST ?? 'dist'), core = `${dist}/core`;
if (dist === resolve('/') || resolve('.').startsWith(dist + '/') || dist === resolve('.') ||
    ['apps', 'core', 'contracts', 'scripts', 'tests', 'deploy'].some(path => dist === resolve(path) || dist.startsWith(resolve(path) + '/'))) {
  throw new Error('Build output must be outside source directories. Use dist/ or .local/<build-name>/.');
}
const selectedApps = apps.filter(app => target === 'all' || app === target);
const browser = target !== 'cloudflare';
const cloudflare = target === 'all' || target === 'cloudflare';
const outputs = [...(browser ? [core] : []), ...(cloudflare ? [`${dist}/cloudflare`] : []), ...selectedApps.map(app => `${dist}/${app}`)];
const marker = '.tasm-build';
const signature = 'Generated by TASM. Rebuilding replaces this directory.\n';
await mkdir(dist, { recursive: true });
if (await realpath(dist) !== dist) throw new Error('Choose a build destination without symlinked path components.');
// Check every destination before touching any previous build.
for (const directory of outputs) {
  const stat = await lstat(directory).catch(error => { if (error.code !== 'ENOENT') throw error; });
  if (!stat) continue;
  if (stat.isDirectory() && !(await readdir(directory)).length) continue;
  if (stat.isDirectory() && await readFile(`${directory}/${marker}`, 'utf8').catch(() => '') === signature) continue;
  throw new Error(`Refusing to replace ${directory}. Choose a fresh TASM_DIST directory.`);
}
const options = { ...browserOptions, sourcemap: true };
const spec = await RefParser.dereference('contracts/tams/api/TimeAddressableMediaStore.yaml');
if (cloudflare) await buildCloudflare(dist, spec, marker, signature);
if (!browser) process.exit(0);

await rm(core, { recursive: true, force: true });
await mkdir(core, { recursive: true });
await writeFile(`${core}/${marker}`, signature);
buildWasm('tasm-browser', 'browser', 'tasm');
const ajv = new Ajv({ strict: false, allErrors: true, code: { source: true, esm: true } });
addFormats(ajv);
const validators = {}, operations = [];
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!['get', 'head', 'post', 'put', 'delete'].includes(method)) continue;
    const name = `operation${operations.length}`;
    const schema = operation.requestBody?.content?.['application/json']?.schema;
    if (schema) { ajv.addSchema(schema, name); validators[name] = name; }
    operations.push({ path, method: method.toUpperCase(), id: operation.operationId,
      validator: schema ? name : null, required: operation.requestBody?.required ?? false });
  }
}
await writeFile('pkg/validators.js', standalone(ajv, validators));
await writeFile('pkg/operations.json', JSON.stringify(operations));
await writeFile(`${core}/openapi.json`, JSON.stringify({ ...spec, security: [],
  'x-tasm-exceptions': ['Authentication is disabled for this browser-local deployment.', 'Local object URLs are not presigned.'] }));
const coreBundle = await build({ ...coreOptions, sourcemap: true, metafile: true,
  entryPoints: { index: 'core/browser/index.ts', worker: 'core/browser/worker.ts' }, outdir: core });
await cp('pkg/browser/tasm_bg.wasm', `${core}/tasm_bg.wasm`);
for (const file of ['pglite.wasm', 'pglite.data', 'initdb.wasm']) await cp(`node_modules/@electric-sql/pglite/dist/${file}`, `${core}/${file}`);
await cp('core/browser/public.d.ts', `${core}/index.d.ts`);
for (const file of ['LICENSE', 'NOTICE']) await cp(file, `${core}/${file}`);

async function files(directory, prefix = '') {
  const result = [];
  for (const entry of await readdir(`${directory}/${prefix}`, { withFileTypes: true })) {
    const path = prefix + entry.name;
    if (entry.isDirectory()) result.push(...await files(directory, path + '/'));
    else result.push(path);
  }
  return result.sort();
}
async function serviceWorker(directory, homepage = false) {
  const paths = (await files(directory)).filter(path => path !== marker && !path.endsWith('.map') && !path.startsWith('service-worker.') && !path.startsWith('_'));
  // Cache the canonical homepage, avoiding Cloudflare's /index.html redirect.
  const assets = paths.filter(path => path !== 'index.html').concat(homepage ? [''] : []);
  const hash = createHash('sha256').update(await readFile('core/browser/service-worker.ts')).update(JSON.stringify(assets));
  for (const path of paths) hash.update(path).update(await readFile(`${directory}/${path}`));
  const version = hash.digest('hex').slice(0, 20);
  await build({ ...options, entryPoints: ['core/browser/service-worker.ts'], outdir: directory,
    define: { __TASM_ASSETS__: JSON.stringify(assets) } });
  await writeFile(`${directory}/service-worker.js`, (await readFile(`${directory}/service-worker.js`, 'utf8')).replace('__TASM_BUILD__', version));
}
await writeCoreNotices(core, coreBundle.metafile);
await serviceWorker(core);
for (const app of selectedApps) {
  const out = `${dist}/${app}`;
  await rm(out, { recursive: true, force: true });
  await cp(core, out, { recursive: true });
  const sampleDir = 'apps/shared/samples';
  const catalogue = JSON.parse(await readFile(sampleDir + '/manifest.json', 'utf8'));
  const entries = app === 'demo' ? catalogue.filter(sample => sample.id === 'orbit') : catalogue;
  const samplesDir = `${out}/samples`;
  await mkdir(samplesDir);
  await writeFile(samplesDir + '/manifest.json', JSON.stringify(entries));
  const media = new Set(['black.ts', 'silence.ts', ...entries.flatMap(sample => [sample.file, sample.thumbnail].filter(Boolean))]);
  for (const file of media) await cp(`${sampleDir}/${file}`, `${samplesDir}/${file}`);
  const appBundle = await build({ ...options, plugins: [{ name: 'app-samples', setup(builder) {
    builder.onResolve({ filter: /^\.\/samples\/manifest\.json$/ }, () => ({ path: `${samplesDir}/manifest.json` }));
  } }], metafile: true, entryPoints: { [app]: `apps/${app}/main.ts`,
    'preview-worker': 'apps/shared/preview-worker.ts', 'ingest-worker': 'apps/shared/ingest-worker.ts' }, outdir: out });
  await build({ ...options, entryPoints: ['apps/shared/startup.ts'], format: 'iife', outdir: out });
  await writeFile(`${out}/index.html`, appHTML(await readFile(`apps/${app}/index.html`, 'utf8'), app));
  await cp(`apps/${app}/bootstrap.js`, `${out}/bootstrap.js`);
  await cp(`apps/${app}/style.css`, `${out}/${app}.css`);
  await cp('apps/shared/onboarding.css', `${out}/onboarding.css`);
  await cp('apps/shared/branding', `${out}/branding`, { recursive: true });
  await cp('node_modules/@byomakase/omakase-player/dist/omakase-player.css', `${out}/omakase.css`);
  await cp('node_modules/mediabunny/LICENSE', `${out}/mediabunny-LICENSE`);
  await cp('deploy/_headers', `${out}/_headers`);
  await writeAppNotices(out, appBundle.metafile);
  await serviceWorker(out, true);
  console.log(`Built ${app}: ${out}`);
}
